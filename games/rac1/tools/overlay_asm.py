#!/usr/bin/env python3
"""
asm/overlays/<name>.s for every "shared" or "level" function in
config/overlays/functions.tsv (docs/OVERLAYS.md, "Plan" step 1).

  python3 tools/overlays.py dump      # if not already done
  python3 tools/overlay_asm.py
  python3 tools/overlay_asm.py --fix-branches   # after stubs move between files

Needs baserom/overlays/level_NN/{text.bin,manifest.json} (tools/overlays.py
dump) and config/overlays/functions.tsv (tools/overlays.py catalogue).

For each level, this builds a splat-compatible file-splits csv with one
entry per place the catalogue found in that level's text (so every byte of
the level's text is accounted for; gaps -- mostly the trailing zero words
the catalogue's fingerprinting trims off the end of a function -- get an
unnamed filler entry) plus a symbol_addrs file naming every one of those
places with its catalogue name. spimdisasm (run inside the build
container: bash tools/docker/run.sh) is then asked, once per level, to
disassemble the whole text against that forced split -- so its own
function-boundary heuristics never second-guess the catalogue. That
matters here: some catalogued "functions" are a handful of bytes of linker
remnant with no `jr $ra`, which spimdisasm's own analysis would normally
fold into whichever real function comes before them (emitted as a mid
function `alabel` instead of a new `glabel`) unless the boundary is
physically forced like this.

Disassembly runs in two passes per level. spimdisasm only names a `lui`
paired with an `addiu` on its own (an address-of, e.g. taking a function's
or a jump table's address); it never invents a name for one paired with a
load/store (a dereference) unless a symbol already covers that address --
so pass 1 gives it every resident (below 0x15F000) function and data
symbol the executable's own asm already has (see `build_resident_symbols`),
then pass 2 adds, per level, whatever dereferenced address pass 1 still
left as a raw `lui`/load-or-store pair (`scan_for_data_symbols`) -- named
`D_XXXXXXXX` if resident (spimdisasm's own executable-asm table missed it,
e.g. a bss variable with no `asm/data` entry) or `D_LNN_XXXXXXXX` if it is
the level's own data (0x15F000 up to the level's text).

Only the file for each function's *canonical* (level, address) -- see
docs/OVERLAYS.md, "Names" -- is kept, under asm/overlays/<name>.s. Any
name spimdisasm invented on its own (never declared in a symbol_addrs
file) is left as the executable's own func_/D_ addressing when its address
is below 0x15F000 (the resident core, shared unchanged by every level), or
requalified as func_LNN_/D_LNN_/jtbl_LNN_ using the generating level's
number when it is 0x15F000 or above (that level's own lit/bss/data/vtbl
range). This is exactly the docs' "Names" rule, applied after the fact: an
autogenerated name is marked with a throwaway suffix while spimdisasm
still knows which symbols it invented, and the suffix is peeled off (and
the name requalified) once the disassembly is in hand.

The executable's own asm post-processing is re-run over the result:
tools/fix_vu0_macro.py, tools/sn_regnames.py, tools/fix_denormal_floats.py.

JUMP TABLES: a function whose canonical body dispatches through a jump
table (spimdisasm emits a `jtbl_.../jlabel_...` reference) gets its
table(s) emitted after the function, in their own `.section .rodata`
block, with `.word` entries pointing at the function's own (local) labels
-- inserting one where spimdisasm did not already emit it -- so the file
still assembles on its own; see `resolve_jump_tables`. A function whose
jump table cannot be read this way (or that uses the rarer `jlabel_` form)
is left out; see the printed summary and
build-sn/overlays/asm_work/skipped_jumptables.txt for the list.

OUT-OF-RANGE BRANCHES: a conditional branch (not `jal`/`j`/`jr`, whose
26-bit or register targets never overflow) whose retail target lies
outside this function is only safe to leave as a symbolic reference when
that target is *this level's* canonical place for its function -- i.e.
its own asm/overlays file will sit at the same address when linked here,
same as the ordinary "branches into the next function" case
(docs/OVERLAYS.md, "Plan" step 1's caveats). A branch to an executable
function (always a different build, src/game/) or to another level's
canonical place for a shared/level function (a *repeat* here, at a
different address than its own file expects) cannot be resolved that way;
`neutralize_far_branches` turns exactly those into a `.word` of retail's
own encoding, with the original instruction kept as a trailing comment.

Scratch input/output for spimdisasm lives under
build-sn/overlays/asm_work/ (not tracked, safe to delete between runs).
"""
import csv
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = ROOT / "config/overlays/functions.tsv"
DUMP = ROOT / "baserom/overlays"
OUT = ROOT / "asm/overlays"
WORK = ROOT / "build-sn/overlays/asm_work"
DOCKER_RUN = ROOT / "tools/docker/run.sh"
# The post-processing scripts use 3.10+ syntax (`str | None`); this repo's
# host convention is /opt/homebrew/bin/python3 (see docs/claude-memory),
# falling back to whatever ran this script if that is not present.
HOST_PYTHON = "/opt/homebrew/bin/python3" if Path("/opt/homebrew/bin/python3").exists() else sys.executable

RESIDENT_MAX = 0x15F000          # below this: resident core, keeps the executable's names
SUFFIX = "_OVLAUTOGEN"           # marks a spimdisasm-autogenerated name until we requalify it

# The resident core's own data records (config/splat.yaml): "core"'s
# subsegments core_text/core_data/core_rdata/core_bss (vram = 0x100080 +
# file-offset - 0x1000), then "main"'s first subsegment core_lit, which
# runs up to RESIDENT_MAX. Only used to bound the last dlabel's size in
# each file parsed by build_resident_symbols.
CORE_TEXT_DIR = ROOT / "asm/nonmatchings/core_text"
CORE_DATA_S = ROOT / "asm/data/core_data.data.s"
CORE_RDATA_S = ROOT / "asm/data/core_rdata.rodata.s"
CORE_LIT_S = ROOT / "asm/data/core_lit.rodata.s"
CORE_RDATA_START = 0x00152300
CORE_BSS_START = 0x00154200
RESIDENT_SYMS_PATH = WORK / "resident_symbols.txt"

SYM_RE = re.compile(rf"\b(D_|func_|jtbl_|jlabel_)([0-9A-Fa-f]{{8}}){re.escape(SUFFIX)}\b")
LOCAL_RE = re.compile(rf"(\.L[0-9A-Fa-f]+){re.escape(SUFFIX)}")
SIZE_RE = re.compile(r"nonmatching\s+\S+,\s*(0x[0-9A-Fa-f]+)")


def parse_catalogue():
    rows = []
    with CATALOGUE.open() as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            name, kind, size, _fp, _nlevels, places = line.split("\t")
            place_list = []
            for p in places.split(","):
                lv, addr = p.split(":")
                place_list.append((int(lv), int(addr, 16)))
            rows.append({"name": name, "kind": kind, "size": int(size), "places": place_list})
    return rows


def level_ids():
    return sorted(int(p.name.split("_")[1]) for p in DUMP.glob("level_*") if (p / "manifest.json").exists())


def build_level_data(rows):
    """level -> {address: (name, size)} for every place in that level, and
    name -> (level, address, size, kind) for the canonical place of every
    shared/level row."""
    level_entries: dict[int, dict[int, tuple[str, int]]] = {}
    targets = {}
    for row in rows:
        places = row["places"]
        canonical = min(places)
        if row["kind"] in ("shared", "level"):
            targets[row["name"]] = (canonical[0], canonical[1], row["size"], row["kind"])
        for lv, addr in places:
            entries = level_entries.setdefault(lv, {})
            if addr in entries:
                raise SystemExit(f"level {lv:02d}: duplicate function start at {addr:08X} "
                                  f"({entries[addr][0]} and {row['name']})")
            entries[addr] = (row["name"], row["size"])
    return level_entries, targets


_MANIFEST_CACHE: dict[int, dict] = {}


def level_manifest(lv):
    if lv not in _MANIFEST_CACHE:
        _MANIFEST_CACHE[lv] = json.loads((DUMP / f"level_{lv:02d}/manifest.json").read_text())
    return _MANIFEST_CACHE[lv]


def manifest_records(lv):
    return {r["name"]: r for r in level_manifest(lv)["records"]}


def text_record(manifest):
    return next(r for r in manifest["records"] if r["name"] == "text")


def build_boundaries(entries, text_addr, text_end):
    """[(address, name_or_None, size)] tiling [text_addr, text_end) exactly.
    name is None for filler gaps: mostly the trailing zero words the
    catalogue's fingerprinting trims off a function's declared size, or
    (at the very start of a level's text) a few words of alignment
    padding before the first real function."""
    items = sorted(entries.items())
    out = []
    cur = text_addr
    for addr, (name, size) in items:
        if addr < cur:
            raise SystemExit(f"overlapping function start at {addr:08X} (cur {cur:08X})")
        if addr > cur:
            out.append((cur, None, addr - cur))
        out.append((addr, name, size))
        cur = addr + size
    if cur < text_end:
        out.append((cur, None, text_end - cur))
    elif cur > text_end:
        raise SystemExit(f"function runs past end of text: {cur:08X} > {text_end:08X}")
    return out


def write_level_inputs(boundaries, text_addr, text_end, level_dir):
    level_dir.mkdir(parents=True, exist_ok=True)
    csv_path = level_dir / "splits.csv"
    sym_path = level_dir / "symbols.txt"
    with csv_path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["0", format(text_addr, "X"), ".text"])
        for addr, name, _size in boundaries:
            fname = f"gap{addr:08X}" if name is None else f"f{addr:08X}"
            w.writerow([format(addr - text_addr, "X"), format(addr, "X"), fname])
        w.writerow([format(text_end - text_addr, "X"), format(text_end, "X"), ".end"])
    with sym_path.open("w") as f:
        for addr, name, size in boundaries:
            if name is not None:
                f.write(f"{name} = 0x{addr:X}; // type:func size:0x{size:X}\n")
    return csv_path, sym_path


# ---------------------------------------------------------------------------
# Resident (below RESIDENT_MAX) symbol table, from the executable's own asm.
# ---------------------------------------------------------------------------

def build_resident_symbols():
    """[(address, name, size, "func"|"data")] for every function in
    asm/nonmatchings/core_text and every dlabel in core_data/core_rdata/
    core_lit -- i.e. everything resident (shared unchanged by every level)
    that the executable's own asm already names. A data symbol's size runs
    to the next dlabel in its file, or to the file's own end boundary for
    the last one."""
    entries = []
    for path in sorted(CORE_TEXT_DIR.glob("*.s")):
        text = path.read_text()
        m_name = re.search(r"^glabel (func_[0-9A-Fa-f]{8})", text, re.M)
        m_size = SIZE_RE.search(text)
        if not m_name or not m_size:
            continue
        addr = int(m_name.group(1)[len("func_"):], 16)
        entries.append((addr, m_name.group(1), int(m_size.group(1), 16), "func"))

    for path, file_end in ((CORE_DATA_S, CORE_RDATA_START),
                            (CORE_RDATA_S, CORE_BSS_START),
                            (CORE_LIT_S, RESIDENT_MAX)):
        text = path.read_text()
        labels = sorted(int(a, 16) for a in re.findall(r"^dlabel D_([0-9A-Fa-f]{8})", text, re.M))
        for i, addr in enumerate(labels):
            end = labels[i + 1] if i + 1 < len(labels) else file_end
            entries.append((addr, f"D_{addr:08X}", end - addr, "data"))
    return entries


def write_resident_symbols(path):
    entries = build_resident_symbols()
    with path.open("w") as f:
        for addr, name, size, kind in sorted(entries):
            f.write(f"{name} = 0x{addr:08X}; // type:{kind} size:0x{size:X}\n")
    return len(entries)


# ---------------------------------------------------------------------------
# Pass 2: a level's own (0x15F000..text) data symbols, found from pass 1's
# leftover raw `lui`/load-or-store pairs.
# ---------------------------------------------------------------------------

_HI_RE = re.compile(r"lui\s+(\$\w+),\s*\(0x([0-9A-Fa-f]+)\s*>>\s*16\)")
_LOAD_STORE_OPS = {
    "lb", "lbu", "lh", "lhu", "lw", "lwu", "ld",
    "sb", "sh", "sw", "sd", "lq", "sq",
    "lwc1", "swc1", "ldc1", "sdc1", "lwc2", "swc2", "lqc2", "sqc2",
}
_LABEL_LINE_RE = re.compile(r"^\s*\.L[0-9A-Fa-f]+")
# spimdisasm shows an unresolved dereference two ways: as two independent
# raw fields (a plain, possibly negative, hex offset -- when it did not
# even recognize the `lui` as paired with this instruction), or, when it
# did recognize the pair but still found no symbol, as the same
# reconstructed address masked onto both instructions (`(0x... & 0xFFFF)`,
# the low half). The latter form is also how it displays an actual 32-bit
# constant built via `ori`/`andi` (never a load/store), so restricting
# this to load/store mnemonics (_LOAD_STORE_OPS) is what keeps that case
# out.
_PAIR_RE = re.compile(
    r"\*/\s+(\w+)\s+\$\w+,\s*(?:(-?0x[0-9A-Fa-f]+)|\(0x([0-9A-Fa-f]+) & 0xFFFF\))\((\$\w+)\)\s*$"
)


def scan_for_data_symbols(lv, split_dir, text_addr):
    """address -> proposed name, for every `lui $r, (0x... >> 16)` in
    split_dir's output immediately followed (within a couple of
    instructions, stopping at a label) by a load/store using `$r` as its
    base register -- i.e. a dereferenced hi/lo pair spimdisasm left
    unresolved (see the module docstring). Addresses below RESIDENT_MAX
    are named as the executable would (build_resident_symbols missed
    them, e.g. a core bss variable); addresses below `text_addr` are this
    level's own data. Anything else (huge values, plain 32-bit constants
    built the same way) is left alone."""
    found: dict[int, str] = {}
    for path in split_dir.glob("**/*.s"):
        lines = path.read_text().splitlines()
        for i, line in enumerate(lines):
            m = _HI_RE.search(line)
            if not m:
                continue
            reg, hi_hex = m.group(1), m.group(2)
            hi_val = int(hi_hex, 16)
            for j in range(i + 1, min(i + 3, len(lines))):
                line2 = lines[j]
                if _LABEL_LINE_RE.match(line2):
                    break
                m2 = _PAIR_RE.search(line2)
                if m2 and m2.group(1) in _LOAD_STORE_OPS and m2.group(4) == reg:
                    if m2.group(3) is not None:
                        addr = int(m2.group(3), 16)
                    else:
                        addr = (hi_val + int(m2.group(2), 16)) & 0xFFFFFFFF
                    if addr < RESIDENT_MAX:
                        found[addr] = f"D_{addr:08X}"
                    elif addr < text_addr:
                        found[addr] = f"D_L{lv:02d}_{addr:08X}"
                    break
    return found


def write_extra_symbols(jobs):
    total = 0
    for job in jobs:
        found = scan_for_data_symbols(job["level"], Path(job["out_split"]), int(job["vram"], 16))
        path = Path(job["symbols"]).parent / "extra_data_symbols.txt"
        with path.open("w") as f:
            for addr, name in sorted(found.items()):
                f.write(f"{name} = 0x{addr:08X}; // type:data size:0x4\n")
        job["extra_symbols"] = str(path)
        total += len(found)
    return total


# ---------------------------------------------------------------------------
# Jump tables: emit the table itself after the function, in its own
# .rodata block, pointing at the function's own (local) labels.
# ---------------------------------------------------------------------------

_JTBL_REF_RE = re.compile(r"jtbl_(?:L\d{2}_)?[0-9A-Fa-f]{8}(?:" + re.escape(SUFFIX) + r")?")
_JTBL_ADDR_RE = re.compile(r"jtbl_(?:L\d{2}_)?([0-9A-Fa-f]{8})")


def read_jump_table_entries(lv, jtbl_addr, func_start, func_end):
    """The jump table's entries (as absolute addresses), read from the
    level's data record (docs/OVERLAYS.md, "Layout"), or its lit record if
    the address isn't in data's range. Reading stops at the first entry
    that doesn't point inside this level's text at all -- almost always
    the function itself, but a few tables' entries land in the very next
    function(s) instead (a computed jump straight into shared code, no
    case bodies of its own); resolve_jump_tables emits those as a plain
    `.word` of the address rather than a local label."""
    records = manifest_records(lv)
    text = records["text"]
    for rec_name in ("data", "lit"):
        rec = records.get(rec_name)
        if rec is None or not (rec["address"] <= jtbl_addr < rec["address"] + rec["bytes"]):
            continue
        raw = (DUMP / f"level_{lv:02d}" / f"{rec_name}.bin").read_bytes()
        offset = jtbl_addr - rec["address"]
        entries = []
        while offset + 4 <= len(raw):
            word = int.from_bytes(raw[offset:offset + 4], "little")
            if not (text["address"] <= word < text["address"] + text["bytes"]):
                break
            entries.append(word)
            offset += 4
        if entries:
            return entries
    return []


def ensure_local_label(lines, addr):
    """Insert a `.L%08X:` label before the instruction at `addr` if
    spimdisasm did not already emit one there (needed for every jump
    table entry: a case reached only through the table has no other
    branch to give it a label)."""
    tag = f"{addr:08X}"
    label_re = re.compile(rf"^\s*\.L{tag}(?:{re.escape(SUFFIX)})?:\s*$")
    if any(label_re.match(line) for line in lines):
        return
    instr_re = re.compile(rf"^\s*/\* [0-9A-Fa-f]+ {tag} [0-9A-Fa-f]{{8}} \*/")
    for i, line in enumerate(lines):
        if instr_re.match(line):
            lines.insert(i, f"  .L{tag}:\n")
            return
    raise ValueError(f"address {tag} is not an instruction in this function")


def resolve_jump_tables(content, lv, func_start, func_end):
    """Append each jump table `content` references as its own `.rodata`
    block after the function, then switch back to `.text` so a function
    written right after this one in the same INCLUDE_ASM'd file lands in
    the right section. An entry inside this function points at one of its
    local labels (inserting the label if spimdisasm did not already emit
    one); the rare entry that instead lands in the next function or two
    (a computed jump with no case body of its own here) is emitted as a
    plain `.word` of that address, needing no label. Returns None if a
    table's entries could not be read (left for the caller to treat as
    still unhandled)."""
    names = sorted(set(_JTBL_REF_RE.findall(content)))
    if not names:
        return content
    lines = content.splitlines(keepends=True)
    blocks = []
    for qualified_name in names:
        addr = int(_JTBL_ADDR_RE.search(qualified_name).group(1), 16)
        entries = read_jump_table_entries(lv, addr, func_start, func_end)
        if not entries:
            return None
        try:
            for e in entries:
                if func_start <= e < func_end:
                    ensure_local_label(lines, e)
        except ValueError:
            return None
        words = "".join(
            f"    .word .L{e:08X}\n" if func_start <= e < func_end else f"    .word 0x{e:08X}\n"
            for e in entries
        )
        # dlabel/enddlabel, not glabel/endlabel: a jump table is data
        # (retail's own asm/data/data.data.s uses the same pair for its
        # jtbl_ symbols), and glabel's .ent/.end pairing would otherwise
        # misparse against the next INCLUDE_ASM'd function in the file.
        blocks.append(f"dlabel {qualified_name}\n{words}enddlabel {qualified_name}\n")
    content = "".join(lines).rstrip("\n") + "\n"
    content += ".section .rodata\n.align 3\n" + "".join(blocks) + ".section .text\n"
    return content


# ---------------------------------------------------------------------------
# Out-of-range branches: neutralize into a `.word` of retail's own bytes.
# ---------------------------------------------------------------------------

_BRANCH_LINE_RE = re.compile(
    r"^(?P<pre>\s*/\* [0-9A-Fa-f]+ )(?P<vaddr>[0-9A-Fa-f]{8})(?P<mid> )(?P<bytes>[0-9A-Fa-f]{8})"
    r"(?P<post> \*/)(?P<sp>\s+)(?P<text>\S.*\S|\S)[ \t]*$"
)
# 16-bit-relative branch opcodes/rt-selectors only: `j`/`jal`/`jr`/`jalr`
# use a 26-bit target or a register and never overflow across this
# project's whole (well under 32MB) address space.
_REL_BRANCH_OPCODES = {0x04, 0x05, 0x06, 0x07, 0x14, 0x15, 0x16, 0x17}
_REGIMM_BRANCH_RT = {0x00, 0x01, 0x02, 0x03, 0x10, 0x11, 0x12, 0x13}


def branch_target(word, vaddr):
    opcode = (word >> 26) & 0x3F

    def rel():
        imm = word & 0xFFFF
        if imm & 0x8000:
            imm -= 0x10000
        return (vaddr + 4 + imm * 4) & 0xFFFFFFFF

    if opcode in _REL_BRANCH_OPCODES:
        return rel()
    if opcode == 0x01 and ((word >> 16) & 0x1F) in _REGIMM_BRANCH_RT:
        return rel()
    if opcode in (0x11, 0x12) and ((word >> 21) & 0x1F) == 0x08:  # COP1/COP2 BC
        return rel()
    return None


def neutralize_far_branches(content, lv, func_start, func_end, level_entries, targets):
    """Turn a conditional branch whose retail target lies outside this
    function into a `.word` of retail's own bytes, unless the target is
    this level's own canonical place for its function (its asm/overlays
    file will sit at the same address when this file is linked here, so
    the reference resolves the same way the docs' "next function" case
    already does). See the module docstring."""
    entries = level_entries.get(lv, {})
    out_lines = []
    changed = 0
    for line in content.splitlines(keepends=True):
        m = _BRANCH_LINE_RE.match(line)
        if not m:
            out_lines.append(line)
            continue
        vaddr = int(m.group("vaddr"), 16)
        word = int.from_bytes(bytes.fromhex(m.group("bytes")), "little")
        target = branch_target(word, vaddr)
        if target is None or func_start <= target < func_end:
            out_lines.append(line)
            continue
        tname, _tsize = entries.get(target, (None, None))
        canonical = targets.get(tname)
        if canonical is not None and canonical[:2] == (lv, target):
            out_lines.append(line)
            continue
        comment = m.group("text").strip()
        newline = "\n" if line.endswith("\n") else ""
        out_lines.append(
            f"{m.group('pre')}{m.group('vaddr')}{m.group('mid')}{m.group('bytes')}{m.group('post')}"
            f"{m.group('sp')}.word 0x{word:08X} /* {comment} */{newline}"
        )
        changed += 1
    return "".join(out_lines), changed


_STUB_OR_DEF_RE = re.compile(r"\b(func_L\d\d_[0-9A-Fa-f]{8})\b")
_FUNC_TARGET_RE = re.compile(r"\bfunc_L\d\d_[0-9A-Fa-f]{8}\b")


def source_files() -> dict:
    """name -> the src/overlays/ file that stubs or defines it (its first
    mention at the start of a line there)."""
    out = {}
    for path in sorted((ROOT / "src/overlays").glob("*/*.c")):
        for line in path.read_text(errors="replace").splitlines():
            if line.startswith("INCLUDE_ASM") or (line[:1].isalpha() and not line.startswith("extern")):
                m = _STUB_OR_DEF_RE.search(line)
                if m:
                    out.setdefault(m.group(1), path)
    return out


def neutralize_cross_file(content, name, files):
    """A branch kept symbolic because its target is a function of this
    level only assembles when that function's stub is in the same source
    file. The generator assumes tools/overlay_src.py's layout; stubs added
    later (tools/overlay_variants.py) can sit elsewhere. Where they do,
    write the branch as retail's word, like any other far branch."""
    home = files.get(name)
    out_lines, changed = [], 0
    for line in content.splitlines(keepends=True):
        m = _BRANCH_LINE_RE.match(line)
        t = _FUNC_TARGET_RE.search(m.group("text")) if m else None
        word = int.from_bytes(bytes.fromhex(m.group("bytes")), "little") if m else 0
        if (not t or m.group("text").startswith(".word") or branch_target(word, int(m.group("vaddr"), 16)) is None
                or home is None or files.get(t.group(0)) == home):
            out_lines.append(line)
            continue
        newline = "\n" if line.endswith("\n") else ""
        out_lines.append(
            f"{m.group('pre')}{m.group('vaddr')}{m.group('mid')}{m.group('bytes')}{m.group('post')}"
            f"{m.group('sp')}.word 0x{word:08X} /* {m.group('text').strip()} */{newline}")
        changed += 1
    return "".join(out_lines), changed


def fix_branches() -> None:
    """The cross-file pass alone, over the asm/overlays files already there
    (after stubs move between files, without an hour of disassembly)."""
    files = source_files()
    total = 0
    for path in sorted(OUT.glob("func_L*.s")):
        content, n = neutralize_cross_file(path.read_text(), path.stem, files)
        if n:
            path.write_text(content)
            total += n
            print(f"{path.name}: {n}")
    print(f"{total} cross-file branch(es) written as words")


def _dispatch(jobs):
    """Run spimdisasm over every job -- in-process if it's already
    importable (e.g. this script is itself running inside the build
    container), otherwise via one `tools/docker/run.sh` call."""
    if _have_spimdisasm():
        _run_jobs(jobs)
        return
    jobs_path = WORK / "jobs.json"
    jobs_path.write_text(json.dumps(jobs))
    subprocess.run(
        ["bash", str(DOCKER_RUN), "python", str(Path(__file__).resolve()), "_worker", str(jobs_path)],
        cwd=ROOT, check=True)


def _run_jobs(jobs):
    """Needs spimdisasm (only installed in the build container). One process,
    one call per level -- avoids re-starting the container or re-parsing
    each level's symbol_addrs per function."""
    from spimdisasm.singleFileDisasm.SingleFileDisasmInternals import (  # type: ignore
        getArgsParser, processArguments)

    parser = getArgsParser()
    for job in jobs:
        sym_files = [str(RESIDENT_SYMS_PATH), job["symbols"]]
        if job.get("extra_symbols"):
            sym_files.append(job["extra_symbols"])
        argv = [
            job["text_bin"], job["out_whole"],
            "--vram", job["vram"],
            "--start", "0x0",
            "--end", job["end"],
            "--file-splits", job["splits"],
            "--split-functions", job["out_split"],
        ]
        for sp in sym_files:
            argv += ["--symbol-addrs", sp]
        argv += [
            "--instr-category", "r5900",
            "--compiler", "EEGCC",
            "--endian", "little",
            "--opcode-ljust", "10",
            "--custom-suffix", SUFFIX,
            "--no-glabel-count",
            "--no-use-fpccsr",
            "--no-cop0-named-registers",
            "--no-name-vars-by-section",
            "--no-name-vars-by-type",
            "--no-name-vars-by-file",
            "--quiet",
        ]
        args = parser.parse_args(argv)
        rc = processArguments(args)
        if rc:
            sys.exit(f"level {job['level']:02d}: spimdisasm exited {rc}")
        print(f"level {job['level']:02d}: disassembled")


def _worker_main(jobs_path):
    _run_jobs(json.loads(Path(jobs_path).read_text()))


def _have_spimdisasm() -> bool:
    try:
        import spimdisasm  # noqa: F401
        return True
    except ImportError:
        return False


BRANCH_LINE = re.compile(r"^(\s*/\* [0-9A-F]+ [0-9A-F]{8} ([0-9A-F]{8}) \*/\s+)"
                         r"(b(?!reak)[a-z0-9.]*)(\s+)(.*?(\.L[0-9A-F]+))\s*$")
LABEL_LINE = re.compile(r"^\s*(\.L[0-9A-F]+):\s*$")


def word_backward_branches(content: str) -> tuple[str, int]:
    """Write every backward branch as a `.word` of retail's encoding, with
    the instruction in a comment. GNU as pads short loops for the R5900
    erratum, and after a forward branch its count goes wrong for the next
    backward branches: it inserts nops retail's assembler did not
    (func_L00_002422D8). It cannot pad a `.word`; nothing else changes."""
    seen, out, n = set(), [], 0
    for line in content.split("\n"):
        if (m := LABEL_LINE.match(line)):
            seen.add(m.group(1))
        elif (m := BRANCH_LINE.match(line)) and m.group(6) in seen:
            word = int.from_bytes(bytes.fromhex(m.group(2)), "little")
            line = f"{m.group(1)}.word 0x{word:08X} /* {m.group(3)}{m.group(4)}{m.group(5)} */"
            n += 1
        out.append(line)
    return "\n".join(out), n


RAM_END = 0x02000000             # main RAM; above it (scratchpad 0x70000000) are constants
HWADDR_RE = re.compile(r"%(hi|lo)\((?:D|func)_(?:L\d\d_)?([0-9A-F]{8})\)")


def unname_hardware(content: str) -> str:
    """Write %hi/%lo of an address outside main RAM (the scratchpad) as the
    plain number: it is a constant in the code, not a symbol."""
    def repl(m: re.Match) -> str:
        addr = int(m.group(2), 16)
        if addr < RAM_END:
            return m.group(0)
        if m.group(1) == "hi":
            return f"0x{((addr + 0x8000) >> 16) & 0xFFFF:X}"
        lo = addr & 0xFFFF
        return f"0x{lo:X}" if lo < 0x8000 else f"-0x{0x10000 - lo:X}"
    return HWADDR_RE.sub(repl, content)


PAIRED_LO = re.compile(r"^(\s*/\*[^*]*\*/\s+)(l[bhwdq]u?|lwc1|lqc2|s[bhwdq]|swc1|sqc2|addiu)(\s+.*?)"
                       r"\(0x([0-9A-F]+) & 0xFFFF\)(.*)$")


def name_paired_addresses(content: str, level: int) -> str:
    """Name a data address spimdisasm paired but left as numbers,
    `(0xADDR >> 16)` / `(0xADDR & 0xFFFF)` in a load, store or addiu, by the
    docs' rule: D_XXXXXXXX below 0x15F000, D_LNN_XXXXXXXX above. `ori`
    pairs are constants (the compiler never builds an address with ori)."""
    named, out = {}, []
    for line in content.split("\n"):
        m = PAIRED_LO.match(line)
        if m and 0x100000 <= int(m.group(4), 16) < RAM_END:
            addr = int(m.group(4), 16)
            named[addr] = f"D_{addr:08X}" if addr < RESIDENT_MAX else f"D_L{level:02d}_{addr:08X}"
            line = f"{m.group(1)}{m.group(2)}{m.group(3)}%lo({named[addr]}){m.group(5)}"
        out.append(line)
    content = "\n".join(out)
    for addr, name in named.items():
        content = re.sub(rf"(lui\s+\$\d+, )\(0x{addr:X} >> 16\)", rf"\g<1>%hi({name})", content)
    return content


def qualify(content: str, level: int) -> str:
    """Peel the autogen suffix off, requalifying anything spimdisasm named
    on its own that falls in this level's own range (docs/OVERLAYS.md,
    "Names")."""
    def repl(m: re.Match) -> str:
        prefix, addr_hex = m.group(1), m.group(2)
        if int(addr_hex, 16) >= RESIDENT_MAX:
            return f"{prefix}L{level:02d}_{addr_hex}"
        return f"{prefix}{addr_hex}"
    content = SYM_RE.sub(repl, content)
    content = LOCAL_RE.sub(r"\1", content)
    return content


def generate(levels=None):
    rows = parse_catalogue()
    level_entries, targets = build_level_data(rows)
    ids = levels if levels is not None else level_ids()

    WORK.mkdir(parents=True, exist_ok=True)
    n_resident = write_resident_symbols(RESIDENT_SYMS_PATH)
    print(f"resident symbol table: {n_resident} entries ({RESIDENT_SYMS_PATH.relative_to(ROOT)})")

    jobs = []
    canonical_paths: dict[str, tuple[Path, int, int]] = {}  # name -> (path, level, size)
    for lv in ids:
        manifest = level_manifest(lv)
        text = text_record(manifest)
        text_addr, text_size = text["address"], text["bytes"]
        boundaries = build_boundaries(level_entries.get(lv, {}), text_addr, text_addr + text_size)

        level_dir = WORK / f"level_{lv:02d}"
        csv_path, sym_path = write_level_inputs(boundaries, text_addr, text_addr + text_size, level_dir)
        split_dir = level_dir / "split"
        jobs.append({
            "level": lv,
            "text_bin": str(DUMP / f"level_{lv:02d}/text.bin"),
            "vram": hex(text_addr),
            "end": hex(text_size),
            "splits": str(csv_path),
            "symbols": str(sym_path),
            "out_whole": str(level_dir / "whole"),
            "out_split": str(split_dir),
        })
        for addr, name, size in boundaries:
            if name is not None and name in targets and targets[name][:2] == (lv, addr):
                canonical_paths[name] = (split_dir / f"f{addr:08X}" / f"{name}.s", lv, size)

    src_files = source_files()
    print(f"disassembling {len(jobs)} level(s) with spimdisasm, pass 1/2 (resident + function symbols)...")
    _dispatch(jobs)
    n_extra = write_extra_symbols(jobs)
    print(f"pass 2/2: {n_extra} level-own data symbol(s) found from pass 1's leftovers, re-disassembling...")
    _dispatch(jobs)

    OUT.mkdir(parents=True, exist_ok=True)
    written, skipped_jtbl, missing, bad_size = [], [], [], []
    n_jtbl_resolved = n_branches_neutralized = 0
    for name, (path, lv, size) in sorted(canonical_paths.items()):
        if not path.exists():
            missing.append(name)
            continue
        content = path.read_text()
        if "jlabel_" in content:
            skipped_jtbl.append(name)
            continue
        m = SIZE_RE.search(content)
        if not m or int(m.group(1), 16) != size:
            bad_size.append(name)
            continue
        addr = targets[name][1]
        if "jtbl_" in content:
            resolved = resolve_jump_tables(content, lv, addr, addr + size)
            if resolved is None:
                skipped_jtbl.append(name)
                continue
            content = resolved
            n_jtbl_resolved += 1
        content = qualify(content, lv)
        content = unname_hardware(content)
        content = name_paired_addresses(content, lv)
        content, n_branch = neutralize_far_branches(content, lv, addr, addr + size, level_entries, targets)
        n_branches_neutralized += n_branch
        content, n_branch = neutralize_cross_file(content, name, src_files)
        n_branches_neutralized += n_branch
        content, _ = word_backward_branches(content)
        if targets[name][1] % 8:
            # Like the executable's asm: `.align 3` only where retail's
            # function starts on 8 bytes; here it would pad.
            content = content.replace(".align 3\n", "", 1)
        if SUFFIX in content:
            print(f"warning: {name}: autogen suffix survived requalification", file=sys.stderr)
        (OUT / f"{name}.s").write_text(content)
        written.append(name)

    if skipped_jtbl:
        (WORK / "skipped_jumptables.txt").write_text("\n".join(skipped_jtbl) + "\n")

    for script in ("fix_vu0_macro.py", "sn_regnames.py", "fix_denormal_floats.py"):
        subprocess.run([HOST_PYTHON, str(ROOT / "tools" / script), str(OUT)], cwd=ROOT, check=True)

    print(f"wrote {len(written)} file(s) to {OUT.relative_to(ROOT)}")
    print(f"resolved {n_jtbl_resolved} jump-table function(s); neutralized {n_branches_neutralized} "
          f"out-of-range branch(es) into raw .word")
    if skipped_jtbl:
        print(f"skipped {len(skipped_jtbl)} function(s) with an unhandled jump table "
              f"(see {(WORK / 'skipped_jumptables.txt').relative_to(ROOT)}): "
              + ", ".join(skipped_jtbl[:10]) + (", ..." if len(skipped_jtbl) > 10 else ""))
    if missing:
        print(f"MISSING (spimdisasm did not produce a file): {', '.join(missing)}", file=sys.stderr)
    if bad_size:
        print(f"BAD SIZE (nonmatching header size disagrees with the catalogue): {', '.join(bad_size)}",
              file=sys.stderr)
    if missing or bad_size:
        sys.exit(1)


def main():
    if len(sys.argv) >= 2 and sys.argv[1] == "_worker":
        _worker_main(sys.argv[2])
        return
    levels = None
    if len(sys.argv) >= 2 and sys.argv[1] == "--fix-branches":
        fix_branches()
        return
    if len(sys.argv) >= 2 and sys.argv[1] == "--levels":
        levels = [int(x) for x in sys.argv[2].split(",")]
    generate(levels)


if __name__ == "__main__":
    main()
