#!/usr/bin/env python3
"""Verify and catalogue every boot C witness body extent.

The private linked ELF must first pass tools/boot_c_campaign.py. This emits
metadata only: compiled body extents are evidence, not retail function sizes.
Acceptance is a separate boot-only decision enforced by boot_trial_gate.py.
The witness list is derived from the campaign's own compiled spans, so it grows
with the campaign instead of being hand-maintained.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from boot_assembly import ROOT, TEXT_SIZE, TEXT_START, text_words
from boot_c_campaign import REPLACEMENTS
from compare_boot_slice import compare
from elf import inspect_elf, read_global_functions

OUTPUT = ROOT / "config/boot/witness_boundaries.tsv"


def linked_bodies(linked: Path) -> list[tuple[str, int, int, int]]:
    """Every global function symbol the campaign linked inside a C span.

    One replacement span may carry several compiled bodies: the retail label
    bounds sometimes cover a run of small functions of which only the first is
    named in the embedded symbol table. Each body is bounded by the next body
    in the same span, or by the span end. Ordered by address so the catalogue
    stays stable as bodies are added.
    """
    functions = read_global_functions(linked)
    rows: list[tuple[str, int, int, int]] = []
    for item in REPLACEMENTS:
        inside = sorted((address, name, size) for name, (address, size)
                        in functions.items() if item.start <= address < item.end)
        if not inside:
            # A linked span whose object exposes no global function symbol is not
            # catalogued; the complete-program gate still checks its bytes.
            print(f"note: campaign span 0x{item.start:08X} ({item.name}) exposes no "
                  f"linked function symbol; not catalogued")
            continue
        if inside[0][0] != item.start:
            print(f"note: campaign span 0x{item.start:08X} ({item.name}) starts at "
                  f"0x{inside[0][0]:08X} in the linked image; not catalogued")
            continue
        for index, (address, name, size) in enumerate(inside):
            bound = inside[index + 1][0] if index + 1 < len(inside) else item.end
            rows.append((name, address, size, bound))
    rows.sort(key=lambda row: row[1])
    if len({name for name, _address, _size, _bound in rows}) != len(rows):
        raise ValueError("a linked body symbol appears in two campaign spans")
    return rows


def label_bounds() -> dict[str, tuple[int, int]]:
    with (ROOT / "config/boot/code_intervals.tsv").open(encoding="utf-8", newline="") as file:
        rows = csv.DictReader((line for line in file if not line.startswith("#")),
                              delimiter="\t")
        return {name: (int(row["start"], 16), int(row["end_exclusive"], 16))
                for row in rows for name in row["symbols"].split(" | ")}


def render(rows: list[tuple[str, int, int, int, str]]) -> str:
    lines = ["# Generated by tools/boot_witness_boundaries.py; compiled C bodies, not retail function sizes or acceptance claims.",
             "symbol\tstart\tbody_end\tnext_label\tbody_bytes\tzero_padding_bytes\texit"]
    for name, start, body_end, next_label, exit_kind in rows:
        lines.append(f"{name}\t0x{start:08X}\t0x{body_end:08X}\t0x{next_label:08X}"
                     f"\t{body_end - start}\t{next_label - body_end}\t{exit_kind}")
    return "\n".join(lines) + "\n"


def terminal_kind(word: int) -> str:
    """Describe the observed transfer; a call alone never proves a noreturn callee."""
    if word == 0x03E00008:
        return "jr_ra"
    opcode = word >> 26
    if opcode == 2:
        return "jump"
    if opcode == 3:
        return "call"
    if opcode == 0:
        function = word & 0x3F
        if function in (0x0D, 0x0C):
            return {0x0D: "break", 0x0C: "syscall"}[function]
        if function == 0x08:
            return "jr_reg"
        if function == 0x09:
            return "jr_reg" if (word >> 11) & 0x1F == 0 else "call"
    raise ValueError("witness does not end in a control transfer")


def catalogue_totals(rows: list[tuple[str, int, int, int, str]], replacements=None) -> dict[str, int]:
    """Count object coverage separately: an object may expose several bodies."""
    spans = REPLACEMENTS if replacements is None else replacements
    covered = sum(any(item.start <= start < item.end for _name, start, _end, _next, _exit in rows)
                  for item in spans)
    return {"objects": len(spans), "bodies": len(rows),
            "uncatalogued_object_spans": len(spans) - covered,
            "body_bytes": sum(end - start for _name, start, end, _next, _exit in rows),
            "zero_padding_bytes": sum(nxt - end for _name, _start, end, nxt, _exit in rows)}


def verify(boot: Path, linked: Path) -> list[tuple[str, int, int, int, str]]:
    try:
        import rabbitizer
    except ImportError as error:
        raise ValueError("optional rabbitizer 1.16.2 is required") from error
    if rabbitizer.__version__ != "1.16.2":
        raise ValueError("witness review requires rabbitizer 1.16.2")
    target = json.loads((ROOT / "config/target.json").read_text(encoding="utf-8"))
    words = text_words(boot, target["boot_sha256"])
    exact, count, _digest = compare(boot, linked, TEXT_START, TEXT_SIZE,
                                    target["boot_sha256"])
    if not exact:
        raise ValueError(f"linked boot text differs: {count}/{TEXT_SIZE}")
    reference = inspect_elf(boot)
    candidate = inspect_elf(linked)
    reference_load = next(item for item in reference["programs"] if item["type"] == 1)
    candidate_load = next(item for item in candidate["programs"] if item["type"] == 1)
    reference_raw = boot.read_bytes()[reference_load["file_offset"]:
                                      reference_load["file_offset"] + reference_load["file_size"]]
    candidate_raw = linked.read_bytes()[candidate_load["file_offset"]:
                                        candidate_load["file_offset"] + candidate_load["file_size"]]
    if candidate_load != reference_load or candidate_raw != reference_raw:
        raise ValueError("linked raw PT_LOAD or program header differs from retail")

    targets: set[int] = set()
    for index, word in enumerate(words):
        insn = rabbitizer.Instruction(word, TEXT_START + 4 * index,
                                     rabbitizer.InstrCategory.R5900)
        if insn.isBranch():
            targets.add(insn.getBranchVramGeneric())
        if insn.isJumpWithAddress():
            targets.add(insn.getInstrIndexAsVram())
    bounds = label_bounds()
    label_starts = {start for start, _end in bounds.values()}
    rows: list[tuple[str, int, int, int, str]] = []
    for name, address, size, next_label in linked_bodies(linked):
        body_end = address + size
        if size < 8 or size % 4 or not address < body_end <= next_label:
            raise ValueError(f"invalid witness body extent: {name}")
        if name in bounds:
            label_start, label_next = bounds[name]
            if address != label_start:
                raise ValueError(f"linked body does not start at its boot label: {name}")
            if body_end > label_next:
                raise ValueError(f"body exceeds its boot code interval: {name}")
        elif body_end != next_label:
            # Unnamed retail functions must fill their compiled span exactly.
            raise ValueError(f"unnamed body does not fill its span: {name}")
        terminal = words[(body_end - 8 - TEXT_START) // 4]
        # These are compiled extents, not independently proven retail function
        # boundaries. Record the transfer without inventing callee semantics.
        exit_kind = terminal_kind(terminal)
        padding = words[(body_end - TEXT_START) // 4:(next_label - TEXT_START) // 4]
        if (any(padding)
                or any(body_end <= target < next_label for target in targets)
                or any(body_end <= label < next_label for label in label_starts)):
            raise ValueError(f"nonzero or targeted alignment after {name}")
        rows.append((name, address, body_end, next_label, exit_kind))
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("boot", type=Path)
    parser.add_argument("linked", type=Path)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    rows = verify(args.boot, args.linked)
    content = render(rows)
    if args.write:
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    elif not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
        raise ValueError("witness boundary catalogue is missing or stale; rerun --write")
    totals = catalogue_totals(rows)
    bodies, alignment = totals["body_bytes"], totals["zero_padding_bytes"]
    print(f"{len(rows)} C witness bodies: {bodies} compiled bytes + {alignment} zero "
          f"alignment bytes across {bodies + alignment} measured boot bytes; "
          f"acceptance requires the boot gate")
    print(f"{totals['objects']} compiled objects; "
          f"{totals['uncatalogued_object_spans']} object spans remain uncatalogued")


if __name__ == "__main__":
    main()
