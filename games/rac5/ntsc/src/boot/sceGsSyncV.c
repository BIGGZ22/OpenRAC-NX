typedef struct {
    short sceGsInterMode;
    short sceGsOutMode;
    short sceGsFFMode;
    short sceGsVersion;
    int (*sceGsVSCfunc)(int);
    int sceGsVSCid;
} sceGsGParam;

extern sceGsGParam *sceGsGetGParam(void);
extern int VSync(void);
extern long long VSync2(void);

int sceGsSyncV(int mode) {
    sceGsGParam *gp;
    long long field;
    gp = sceGsGetGParam();
    if (gp->sceGsVSCfunc == 0) {
        VSync();
        if (gp->sceGsInterMode == 1) {
            return (*(volatile unsigned long long *)0x12001000 >> 13) & 1;
        }
    } else {
        field = (VSync2() >> 13) & 1;
        if (gp->sceGsInterMode == 1) {
            return field;
        }
    }
    return 1;
}
