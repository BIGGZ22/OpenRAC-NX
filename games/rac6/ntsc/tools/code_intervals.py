#!/usr/bin/env python3
"""Derive the candidate code interval of every SNR2 module, and catalogue it.

An SNR2 module carries its code between a fixed start and a boundary that the
relocation tables locate exactly: the last jump site (a named ``jal`` or a
packed 26-bit local jump) plus its delay slot, rounded up to the 128-byte
alignment the loader uses.  The interval is the only region of a module that
can hold instructions; everything past it is data.

The catalogue holds metadata only: the interval bounds, its size, the SHA-256
of the interval bytes and the relocation counts that support the boundary.

Adapted from ``OpenRAC/rac5-sm-decomp`` (GPL-3.0); see
``THIRD_PARTY_NOTICES.md``.

Usage:
    python3 tools/code_intervals.py <image> [--write]
"""

from __future__ import annotations

import argparse
import csv
import hashlib
from pathlib import Path

from rel import HEADER, MAGIC, RELOCATION, iter_packed_relocations, unpack_relocation

ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = ROOT / "config/levels/code_intervals.tsv"
CODE_START = 0x80


def code_end_from_relocations(data: bytes) -> int:
    """Return the end of the candidate code interval, from the jump relocations."""
    header = HEADER.unpack_from(data)
    sites: set[int] = set()
    for index in range(header[2]):
        site, kind, _symbol, _addend = unpack_relocation(
            data, header[1] + index * RELOCATION.size)
        if kind == 4:
            sites.add(site)
    sites.update(item.site for item in iter_packed_relocations(data, header[13], header[1])
                 if item.kind == 2)
    if not sites:
        raise ValueError("SNR2 module has no measured jump relocation site")
    return (max(sites) + 8 + 0x7F) & ~0x7F


def trailing_zero_words(data: bytes, end: int) -> int:
    """Count the zero words that follow the last code byte."""
    count = 0
    for offset in range(end - 4, CODE_START - 1, -4):
        if data[offset] | (data[offset + 1] << 8) | (data[offset + 2] << 16) \
                | (data[offset + 3] << 24):
            break
        count += 1
    return count


def module_row(name: str, data: bytes) -> tuple[str, int, int, str, int, int, int]:
    """Return the catalogue row of one module."""
    header = HEADER.unpack_from(data)
    if header[0] != MAGIC or header[11] != len(data) or header[10] != CODE_START:
        raise ValueError(f"{name}: SNR2 header differs from the measured target")
    end = code_end_from_relocations(data)
    if end <= CODE_START or end >= header[1]:
        raise ValueError(f"{name}: derived code interval is out of range")
    named = sum(1 for index in range(header[2])
                if unpack_relocation(data, header[1] + index * RELOCATION.size)[1] == 4)
    local = sum(1 for item in iter_packed_relocations(data, header[13], header[1])
                if item.kind == 2)
    digest = hashlib.sha256(data[CODE_START:end]).hexdigest()
    return (name, end, end - CODE_START, digest, named, local,
            trailing_zero_words(data, end))


def render(rows: list[tuple]) -> str:
    lines = ["# Generated by tools/code_intervals.py; interval bounds and hashes, no game bytes.",
             "module\tstart\tend_exclusive\tinterval_bytes\tsha256\tnamed_jumps\t"
             "packed_jumps\ttrailing_zero_words"]
    for name, end, size, digest, named, local, padding in rows:
        lines.append(f"{name}\t0x{CODE_START:08X}\t0x{end:08X}\t{size}\t"
                     f"{digest}\t{named}\t{local}\t{padding}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("image", type=Path)
    parser.add_argument("--write", action="store_true", help="regenerate the tracked catalogue")
    args = parser.parse_args()

    from disc import IsoDisc
    from rel import module_paths

    rows: list[tuple] = []
    with IsoDisc(args.image) as disc:
        for path in module_paths(disc):
            rows.append(module_row(Path(path).name, disc.file_bytes(path)))

    content = render(rows)
    if args.write:
        CATALOGUE.parent.mkdir(parents=True, exist_ok=True)
        CATALOGUE.write_text(content, encoding="utf-8", newline="\n")
    elif not CATALOGUE.is_file() or CATALOGUE.read_text(encoding="utf-8") != content:
        raise ValueError("code interval catalogue is missing or stale; run with --write")

    total = sum(size for _name, _end, size, *_rest in rows)
    print(f"{len(rows)} modules, {total} candidate code bytes by placement; "
          f"catalogue {'written' if args.write else 'verified'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
