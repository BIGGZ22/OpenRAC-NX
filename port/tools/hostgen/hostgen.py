def write_program_files(program: Program, out: Path, game: str) -> dict:
    head = [
        f"/* Generated by port/tools/hostgen for {game}. Do not edit. */",
    ]
    protos = head + ["#ifndef OPENRAC_GAME_PROTOS_H", "#define OPENRAC_GAME_PROTOS_H",
                     "#include <stdarg.h>", "#include \"openrac/guest.h\"", ""]
    unprototyped = []
    for sym in sorted(program.functions):
        f = program.functions[sym]
        p = prototype(f, program.typedefs)
        if p is None:
            unprototyped.append(sym)
            continue
        protos.append(p + ";")
        if sym in program.wrap:
            protos.append(p.replace(f" {cname(sym)}(", f" {cname(sym)}__game(", 1) + ";")
        if sym in program.hook and sym in program.wrap_host:
            protos.append(p.replace(f" {cname(sym)}(", f" {cname(sym)}__hooked(", 1) + ";")
    protos += ["", "#endif", ""]
    _write(out / "game_protos.h", "\n".join(protos))

    stubs = head + ["#include \"openrac/guest.h\"", "#include \"game_protos.h\"", ""]
    stub_count = 0
    for f in program.stubs():
        p = prototype(f, program.typedefs)
        if p is None:
            continue
        ret = canon(f.sig.ret, program.typedefs)
        # Its own site (guest.h, openrac_reach_site): the calls are counted in a word of its own,
        # and the first is logged, as openrac_guest_missing does.
        kind = "asm" if f.asm else "no-c"
        body = (f"    static openrac_reach_site site_ = {{\"{f.symbol}\", \"{kind}\", 0, 0, 0}};\n"
                f"    openrac_guest_reach(&site_);")
        if ret != "void":
            body += "\n    return 0;"
        stubs.append(f"{p} {{\n{body}\n}}\n")
        stub_count += 1
    _write(out / "stubs.c", "\n".join(stubs))

    # Every function with a code address, per overlay.
    # (The translation's calls through a code address take the type of the function found there:
    # Program.function_at, from the same tables.)
    program._code_tables = None
    code_tables = program.code_tables()
    fn = head + ["#include \"openrac/guest.h\"", "#include \"game_protos.h\"", ""]
    for overlay in sorted(code_tables):
        name = "exe" if overlay < 0 else f"overlay_{overlay:02d}"
        fn.append(f"static const openrac_fn_entry k_{name}[] = {{")
        for addr, sym in sorted(code_tables[overlay]):
            fn.append(f"    {{0x{addr:08X}u, (openrac_host_fn){cname(sym)}, \"{sym}\"}},")
        fn.append("};")
        fn.append("")
    # Each function's thunk, for a call through its address with the EE's registers as they are
    # (guest.h, openrac_guest_call_regs; where OPENRAC_REGS_THUNKS is on: Windows).
    thunks = []
    for sym in sorted({s for entries in code_tables.values() for _a, s in entries}):
        text = thunk_text(sym, program.functions[sym], program.typedefs, len(thunks))
        if text is not None:
            thunks.append((sym, text))
    if thunks:
        fn += ["#if OPENRAC_REGS_THUNKS",
               "static double thunk_d_(uint64_t b) { double d; memcpy(&d, &b, sizeof d); return d; }",
               "static uint64_t thunk_bits_(double d) { uint64_t b; memcpy(&b, &d, sizeof b); return b; }"]
        fn += [text for _sym, text in thunks]
        fn.append("static const openrac_thunk_entry k_thunks[] = {")
        fn += [f"    {{(openrac_host_fn){cname(sym)}, thunk_{k}}}," for k, (sym, _t) in enumerate(thunks)]
        fn += ["};", "#endif", ""]
    fn.append("void openrac_game_register_functions(void) {")
    for overlay in sorted(code_tables):
        name = "exe" if overlay < 0 else f"overlay_{overlay:02d}"
        fn.append(f"    openrac_guest_register({overlay}, k_{name}, sizeof k_{name} / sizeof k_{name}[0]);")
    if thunks:
        fn += ["#if OPENRAC_REGS_THUNKS", "    openrac_guest_register_thunks(k_thunks, sizeof k_thunks / sizeof k_thunks[0]);",
               "#endif"]
    fn.append("}")
    _write(out / "functions.c", "\n".join(fn) + "\n")
    return {"stubs": stub_count, "unprototyped": unprototyped,
            "addresses": sum(len(v) for v in code_tables.values())}


def thunk_text(sym: str, f: Function, typedefs: dict, k: int) -> str | None:
    """thunk_<k>: f called with the EE's argument registers, integers from i[] in order and floats
    from f[], by its definition's parameters; its result as the EE has it (a float in *r). None
    where a parameter or the result has no form there (a record by value)."""
    sig = f.sig
    ret = canon(sig.ret, typedefs)
    if ret is None or ret in ("long double", "va_list"):
        return None
    args: list[str] = []
    if not sig.prototyped:
        args = [f"(int)i[{n}]" for n in range(8)]
    else:
        ni = nf = 0
        for p in sig.params:
            c = canon(p, typedefs)
            if c is None or c in ("va_list", "long double"):
                return None
            if c == "float":
                args.append(f"f[{nf}]" if nf < 8 else "0.0f")
                nf += 1
            elif c == "double":
                args.append(f"thunk_d_(i[{ni}])" if ni < 8 else "0.0")
                ni += 1
            else:
                args.append(f"({c})i[{ni}]" if ni < 8 else f"({c})0")
                ni += 1
        if sig.variadic:
            args += [f"i[{n}]" for n in range(ni, 8)]
    call = f"{cname(sym)}({', '.join(args)})"
    if ret == "void":
        body = f"{call}; return 0;"
    elif ret == "float":
        body = f"*r = {call}; return 0;"
    elif ret == "double":
        body = f"return thunk_bits_({call});"
    else:
        body = f"return (uint64_t)({call});"
    return (f"static uint64_t thunk_{k}(const uint64_t* i, const float* f, float* r) {{ "
            f"(void)i; (void)f; (void)r; {body} }}")


def _c_string(text: str | None) -> str:
    if text is None:
        return "NULL"
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_libraries(program: Program, out: Path, rows: dict, api: dict) -> int:
    """libraries.c: each library address the game's table binds to a shared
    replacement, as a function of that address calling openrac_lib_<name>."""
    lines = ["/* Generated by port/tools/hostgen from the game's libraries.tsv. Do not edit. */",
             "#include \"openrac/guest.h\"", "#include \"game_protos.h\"", ""]
    bound = 0
    for sym, (name, _sig) in sorted(rows.items()):
        if name not in api:
            continue  # the game's own host code provides it (port/game/<id>/host)
        f = program.functions.get(sym)
        shared = Signature.of(ctype.parse(api[name]))
        proto = prototype(f, program.typedefs) if f else None
        shared_proto = prototype(Function(f"openrac_lib_{name}", shared), program.typedefs)
        if proto is None or shared_proto is None:
            continue
        shared_proto = shared_proto.replace(" game_openrac_lib_", " openrac_lib_", 1)
        sig = f.sig
        args = []
        for i, p in enumerate(shared.params):
            c = canon(p, program.typedefs)
            args.append(f"({c})a{i}" if i < len(sig.params) else f"({c})0")
        call = f"openrac_lib_{name}({', '.join(args)})"
        body = f"    {call};" if canon(sig.ret, program.typedefs) == "void" else f"    return {call};"
        if shared.variadic or sig.variadic:
            body = f"    openrac_guest_missing(\"{sym} ({name}): variadic, bind it by hand\");" + (
                "" if canon(sig.ret, program.typedefs) == "void" else "\n    return 0;")
        else:
            lines.append(shared_proto + ";")
        lines += [f"/* {name} */", proto + " {", body, "}", ""]
        bound += 1
    _write(out / "libraries.c", "\n".join(lines))
    return bound


def write_game_info(program: Program, out: Path, cfg: dict) -> None:
    """game_info.c: the game's description, its entry, and its overlay hook."""
    entry = cfg.get("entry")
    lines = ["/* Generated by port/tools/hostgen from the game's hostgen.json. Do not edit. */",
             "#include \"openrac/game_host.h\"", "#include \"game_protos.h\"", "",
             "const openrac_game_info openrac_game = {",
             f"    {_c_string(cfg.get('id'))}, {_c_string(cfg.get('title'))}, {_c_string(cfg.get('game'))},",
             f"    {_c_string(cfg.get('serial'))}, {int(cfg.get('frame_rate', 60))}, {_c_string(entry)},",
             "};", "", "int openrac_game_run(void) {"]
    f = program.functions.get(entry) if entry else None
    if f is None:
        if entry:
            lines.append(f"    openrac_guest_missing(\"{entry} (the game's entry)\");")
            lines.append("    return 1;")
        else:
            lines.append("    return 0; /* the game's main is not known yet */")
    else:
        zeros = ", ".join("0" for _ in f.sig.params) if f.sig.prototyped else ""
        lines.append(f"    {cname(entry)}({zeros});")
        lines.append("    return 1;")
    lines.append("}")
    if not cfg.get("overlay_hook"):
        lines += ["", "/* The game has no overlay hook (hostgen.json): code addresses are the executable's. */",
                  "int openrac_game_loaded_overlay(void) {", "    return OPENRAC_OVERLAY_EXE;", "}"]
    _write(out / "game_info.c", "\n".join(lines) + "\n")


def _write(path: Path, text: str) -> None:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def write_report(out: Path, reports: list[UnitReport], program: Program, extra: dict, game: str) -> dict:
    fns = [f for r in reports for f in r.functions]
    translated = [f for f in fns if f.status == "translated"]
    stubbed = [f for f in fns if f.status == "stub"]
    reasons: dict[str, int] = {}
    for f in stubbed:
        key = f.reason.split(" (")[0] if f.reason.startswith("inline assembly") else f.reason
        reasons[key] = reasons.get(key, 0) + 1
    no_c = [f for f in program.stubs()]
    stage = extra.pop("asm", None) or asmc.Stage()
    asm_reasons: dict[str, int] = {}
    for why in stage.unsupported.values():
        key = re.sub(r",? at [0-9A-F]{8}\b| \([0-9A-F]{8}\)", "", why)
        key = re.sub(r"\$\w+(?:, \$\w+)*", "a register", key)
        key = re.sub(r"\b(?:func|FUN)_\w+|\b[A-Za-z_]\w*(?=, which)", "a function", key)
        asm_reasons[key] = asm_reasons.get(key, 0) + 1
    # What translated assembly calls counts for the frontier like what translated C calls.
    fns_and_asm = fns + [r.report for r in stage.translated if r.report is not None]
    summary = {
        "game": game,
        "units": len(reports),
        "units_unreadable": [r.unit for r in reports if any(p.startswith("Clang could not") for p in r.problems)],
        "functions_translated": len(translated),
        "functions_stubbed": len(stubbed),
        "functions_without_c": len(no_c),
        "functions_without_c_asm": sum(1 for f in no_c if f.asm),
        "functions_without_c_other_spelling": sum(1 for f in no_c if program.canonical(f.symbol) != f.symbol),
        "arguments_passed_through": sum(f.passthrough for f in fns),
        "arguments_filled_with_zero": {f.name: f.zero_args for f in fns if f.zero_args},
        "call_site_mismatches": {f.name: sorted(set(f.mismatches)) for f in fns if f.mismatches},
        "call_graph": {f.name: sorted(f.calls) for f in fns if f.status == "translated" and f.calls},
        "hardware_accesses": sum(f.hw for f in fns),
        "functions_touching_hardware": sorted(f.name for f in fns if f.hw),
        "literal_addresses": {f.name: f.literals for f in fns if f.literals},
        "stub_reasons": dict(sorted(reasons.items(), key=lambda kv: -kv[1])),
        "fixes": {r.unit: r.fixes for r in reports if r.fixes},
        "problems": {r.unit: r.problems for r in reports if r.problems},
        "stubbed": {f.name: f.reason for f in stubbed},
        "inline_assembly_skipped": {f.name: ", ".join(f.asm_skipped) for f in translated if f.asm_skipped},
        "functions_from_assembly": len(stage.translated),
        "from_assembly": {r.name: r.source for r in stage.translated},
        "assembly_unsupported": dict(sorted(stage.unsupported.items())),
        "assembly_unsupported_reasons": dict(sorted(asm_reasons.items(), key=lambda kv: -kv[1])),
        "without_c_or_assembly": sorted(stage.without_asm),
        # Each function with no C or with C from its assembly: where it sits, and the spelling with
        # C its calls go to instead (no_c.py classifies them from this).
        "without_c_places": {
            f.symbol: {"places": [[ov, f"{a:08X}"] for ov, a in program.code_places(f.symbol)],
                       "kind": "asm" if f.asm else "no-c",
                       **({"other_spelling": program.canonical(f.symbol)}
                          if program.canonical(f.symbol) != f.symbol else {})}
            for f in no_c + [program.functions[r.name] for r in stage.translated if r.name in program.functions]},
        **extra,
    }
    summary["call_graph"].update({r.name: sorted(r.report.calls) for r in stage.translated
                                  if r.report is not None and r.report.calls})
    frontier = boot_frontier(fns_and_asm, program, extra.get("roots", []))
    summary["frontier"] = frontier
    (out / "report.json").write_text(json.dumps(summary, indent=1, sort_keys=True) + "\n")
    md = [
        f"# hostgen report: {game}",
        "",
        "| | |",
        "|---|---:|",
        f"| Units read | {summary['units']} |",
        f"| Functions translated | {summary['functions_translated']} |",
        f"| Functions with C that could not be translated (stubs) | {summary['functions_stubbed']} |",
        f"| ... translated without inline assembly the host does not run | "
        f"{len(summary['inline_assembly_skipped'])} |",
        f"| Functions translated from assembly (no C yet; asmc.py) | {summary['functions_from_assembly']} |",
        f"| Functions with no C (still assembly, or libraries) | {summary['functions_without_c']} |",
        f"| ... of them another spelling of a function with C, whose calls go there | "
        f"{summary['functions_without_c_other_spelling']} |",
        f"| Functions from candidates (C that is not the matched C) | {len(extra.get('candidates_used', []))} |",
        f"| Matched functions the port's own C overrides | {len(extra.get('overrides_used', []))} |",
        f"| Functions by code address | {extra.get('addresses', 0)} |",
        f"| Arguments passed through from the caller's registers | {summary['arguments_passed_through']} |",
        f"| Arguments a call leaves out, filled with 0 | "
        f"{sum(len(v) for v in summary['arguments_filled_with_zero'].values())} |",
        f"| Accesses to hardware register addresses | {summary['hardware_accesses']} "
        f"in {len(summary['functions_touching_hardware'])} functions |",
        f"| Literal addresses relocated as their globals would be | "
        f"{sum(len(v) for v in summary['literal_addresses'].values())} "
        f"in {len(summary['literal_addresses'])} functions |",
        "",
        "## Why functions became stubs",
        "",
        *[f"- {n} x {why}" for why, n in summary["stub_reasons"].items()],
        "",
    ]
    if summary["inline_assembly_skipped"]:
        md += [
            "## Inline assembly the host does not run",
            "",
            "These functions are translated with their asm statements skipped (each one an ordering",
            "barrier): what those instructions compute is missing, and the C after them reads whatever",
            "their outputs held. Give such a function C of the port's own (an override, or host C).",
            "",
            "| Function | Instructions skipped |",
            "|---|---|",
            *[f"| {name} | {what} |" for name, what in sorted(summary["inline_assembly_skipped"].items())],
            "",
        ]
    if stage.translated or stage.unsupported:
        md += [
            "## Functions with no C, translated from their assembly",
            "",
            f"{len(stage.translated)} functions the decompilation has no C for run as C written from their",
            f"instructions (asmc.py); {len(stage.unsupported)} with assembly stay stubs, and",
            f"{len(stage.without_asm)} have no assembly here. C in the decompilation replaces a translation.",
            "",
            "Why a function with assembly stays a stub:",
            "",
            *[f"- {n} x {why}" for why, n in summary["assembly_unsupported_reasons"].items()],
            "",
            "| Function | Why it stays a stub |",
            "|---|---|",
            *[f"| {name} | {why} |" for name, why in summary["assembly_unsupported"].items()],
            "",
        ]
    if summary["arguments_filled_with_zero"]:
        md += [
            "## Calls short of arguments, filled with 0",
            "",
            "The callee takes more than the call passes, and the caller has no argument of its own in",
            "that register. On the console the register held whatever the caller last left there, which",
            "the C does not say: check each against the assembly, and pass the value explicitly.",
            "",
            "| Caller | Callee and argument |",
            "|---|---|",
            *[f"| {caller} | {', '.join(args)} |" for caller, args in sorted(summary["arguments_filled_with_zero"].items())],
            "",
        ]
    if frontier["roots"]:
        md += [
            "## The frontier: what the program reaches that has no C",
            "",
            f"From {', '.join(frontier['roots'])}, following direct calls and functions whose address is",
            f"taken: {frontier['reachable']} functions reachable, {len(frontier['missing'])} of them without C",
            "(nearest first; a function is only reached through ones that have C). The port stops",
            "at the first of these it runs; decompiling them moves it on.",
            "",
            "| Function | Depth | Called from |",
            "|---|---:|---|",
            *[f"| {m['name']} | {m['depth']} | {m['from']} |" for m in frontier["missing"]],
            "",
        ]
    (out / "report.md").write_text("\n".join(md))
    return summary


def boot_frontier(fns, program: Program, roots: list[str]) -> dict:
    """Functions reachable from roots, and those among them without C."""
    calls = {f.name: f.calls for f in fns if f.status == "translated"}
    seen = {}
    queue = [(r, 0, "") for r in roots]
    missing = []
    while queue:
        name, depth, parent = queue.pop(0)
        if name in seen:
            continue
        seen[name] = depth
        if name in program.host or name in calls:
            for c in sorted(calls.get(name, ())):
                if c not in seen:
                    queue.append((c, depth + 1, name))
        else:
            missing.append({"name": name, "depth": depth, "from": parent})
    return {"roots": roots, "reachable": len(seen), "missing": missing}


def _files(path: Path):
    if path.is_file():
        yield path
    elif path.is_dir():
        yield from (p for p in path.rglob("*") if p.is_file() and "__pycache__" not in p.parts)


def inputs_digest(source: Path, config: Path, cfg: dict, options: list[str]) -> str:
    """A fingerprint of everything hostgen reads: the decompilation's C and tables, the game's
    configuration, hostgen's own code and the openrac_common modules it imports, the Clang it parses with and the options. Equal
    fingerprints write the same files, so a build whose generated C is already in place (a CI
    cache, a second configure) skips the translation."""
    paths = [source / d for d in sorted(set(cfg["sources"] + cfg["includes"]))]
    paths += [source / t for t in cfg["symbols"]]
    # An alias table outside the include directories (a build's derived values) counts too.
    paths += [source / t for t in cfg.get("aliases", []) if Path(t).suffix == ".json"]
    for key in ("places", "candidates"):
        if cfg.get(key):
            paths.append(source / cfg[key])
    # The table that names the units of another compiler (long_long_128) decides how their C reads.
    if (cfg.get("long_long_128") or {}).get("except_objects"):
        paths.append(source / cfg["long_long_128"]["except_objects"])
    table = source / cfg["candidates"] if cfg.get("candidates") else None
    if table and table.is_file():
        for line in table.read_text().splitlines():
            if line.strip() and not line.startswith("#"):
                paths.append(source / line.partition("\t")[2].strip())
    # The game's own folder and the tables every game shares (port/game/<id>, port/game/common).
    paths += [config.parent, config.parent.parent / "common", HERE / "include"]
    paths += sorted(HERE.glob("*.py"))
    # The shared helpers it reads its tables through (tools/openrac_common) are its code as well.
    paths += sorted(Path(tables.__file__).parent.glob("*.py"))
    h = hashlib.sha256()
    for root in paths:
        for f in sorted(_files(root)):
            h.update(str(f.relative_to(root) if f != root else f.name).encode() + b"\0")
            h.update(hashlib.sha256(f.read_bytes()).digest())
    # The assembly the setup wrote and the player's disc (hostgen.json "asm", --asm, --asm-source,
    # --retail-*): C is translated from them too, so a new setup or a disc set up after a build
    # changes the output. They are large (thousands of files, a disc image), so each file counts
    # by its path, size and time rather than its bytes.
    a = asmc.asm_config(cfg)
    if a:
        h.update(json.dumps(a, sort_keys=True, default=str).encode())
        base = Path(a["source"]) if a.get("source") else source
        stat_roots = [base / d for d in a.get("dirs", [])]
        stat_roots += [Path(v) for v in (a.get("retail") or {}).values() if v]
        for root in stat_roots:
            for f in sorted(_files(root)):
                st = f.stat()
                h.update(f"{f}\0{st.st_size}\0{st.st_mtime_ns}\0".encode())
    try:
        clang = subprocess.run([clangast.clang_binary(), "--version"], capture_output=True, text=True).stdout
    except (OSError, SystemExit):
        clang = ""
    h.update((clang + sys.platform + "\0".join(options)).encode())
    return h.hexdigest()


