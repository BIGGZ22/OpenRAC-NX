_STATE: dict = {}


def _init(state: dict) -> None:
    _STATE.update(state)


def _index_one(rel: str):
    s = _STATE
    unit, err = clangast.parse_unit(s["clang"], s["root"], rel, s["flags"])
    if unit is None:
        return rel, None, [f"Clang could not read it: {err.strip()[:2000]}"], []
    part = Program()
    part.set_names(s["names"].get("code"), s["names"].get("data"))
    part.groups = s["groups"]
    problems = index_unit(part, rel, unit.ast)
    for fix in unit.fixes:
        if fix.startswith("alias "):
            _, name, symbol = fix.split()
            part.aliases[(rel, name)] = symbol
    return rel, part, problems, unit.fixes


def _lower_one(rel: str):
    s = _STATE
    report = UnitReport(rel)
    unit, err = clangast.parse_unit(s["clang"], s["root"], rel, s["flags"])
    out = s["out"] / generated_name(rel)
    if unit is None:
        report.problems.append(f"Clang could not read it: {err.strip()[:2000]}")
        # The build still expects the file: its functions are stubs (stubs.c).
        out.parent.mkdir(parents=True, exist_ok=True)
        _write(out, f"/* Generated by port/tools/hostgen: Clang could not read {rel}; report.md says why.\n"
                    " * Its functions are stubs (stubs.c) until it reads. */\n")
        return report
    report.fixes = unit.fixes
    text = Unit(s["program"], rel, unit.ast, report).emit()
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return report


def generated_name(rel: str) -> str:
    return rel[4:] if rel.startswith("src/") else rel


def load_config(path: Path) -> dict:
    cfg = json.loads(path.read_text())
    cfg.setdefault("sources", ["src"])
    cfg.setdefault("skip", [])
    cfg.setdefault("includes", ["include", "src"])
    cfg.setdefault("defines", [])
    cfg.setdefault("host_functions", [])
    cfg.setdefault("names", {})
    cfg.setdefault("symbols", [])
    cfg.setdefault("groups", [])
    return cfg


def read_table_of_c(table: Path) -> dict[str, str]:
    """name -> C from a "name<TAB>file" table (files relative to the table's
    directory); several names may share one file, which
    then stands for all of them (the same text object)."""
    out: dict[str, str] = {}
    texts: dict[Path, str] = {}
    for line in table.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, _, rel = line.partition("\t")
        path = (table.parent / rel.strip()).resolve()
        if path.is_file():
            if path not in texts:
                texts[path] = path.read_text(encoding="utf-8", errors="surrogateescape")
            out[name.strip()] = texts[path]
    return out


def read_hand(config_dir: Path, cfg: dict) -> dict[str, str]:
    """The port's own C for the game's hand-written assembly (hostgen.json
    "hand": a table beside the game's configuration, files relative to it):
    written from what each retail routine does, in the decompilation's
    dialect, and translated like the game's C."""
    table = cfg.get("hand")
    if not table or not (config_dir / table).is_file():
        return {}
    return read_table_of_c(config_dir / table)


def read_aliases(source: Path, cfg: dict) -> dict[str, str]:
    """The decompilation's readable names, each a macro for an address name (hostgen.json
    "aliases": headers in the decompilation of `#define NAME func_ADDR` lines), or none."""
    out: dict[str, str] = {}
    for header in cfg.get("aliases", []):
        if (source / header).is_file():
            out.update(prep.read_aliases((source / header).read_text(encoding="utf-8", errors="surrogateescape")))
    return out


def read_drafts(config_dir: Path, cfg: dict) -> tuple[str, set[str]] | None:
    """The files whose own pending C is read in place of their assembly stub (hostgen.json
    "drafts": {"guard": the macro the decompilation keeps it under, "units": a list beside the
    game's configuration, one file a line from the decompilation's top, # for comments})."""
    drafts = cfg.get("drafts")
    if not drafts or not (config_dir / drafts["units"]).is_file():
        return None
    units = {line.split("#")[0].strip() for line in (config_dir / drafts["units"]).read_text().splitlines()}
    return drafts["guard"], units - {""}


def read_candidates(source: Path, cfg: dict) -> dict[str, str]:
    """Candidate C for functions the decompilation still has as assembly
    (hostgen.json "candidates": a table in the decompilation, one
    "name<TAB>file" line each, the file relative to the decompilation; lines
    starting with # are comments). A missing table means none: the
    decompilation decides what it offers. Each is C that does what the retail
    function does without matching its bytes; the matching build never sees it."""
    table = cfg.get("candidates")
    if not table or not (source / table).is_file():
        return {}
    out: dict[str, str] = {}
    texts: dict[Path, str] = {}
    for line in (source / table).read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, _, rel = line.partition("\t")
        path = source / rel.strip()
        if path.is_file():
            if path not in texts:
                texts[path] = path.read_text(encoding="utf-8", errors="surrogateescape")
            out[name.strip()] = texts[path]
    return out


def library_api(config_dir: Path, cfg: dict) -> dict[str, str]:
    """The library functions every game shares (port/game/common/libraries.tsv):
    name -> signature, implemented by the port as openrac_lib_<name>."""
    path = config_dir / cfg.get("library_api", "../common/libraries.tsv")
    api = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            cols = line.split("\t")
            if len(cols) >= 3:
                api[cols[0].strip()] = cols[2].strip()
    return api


def host_table(config_dir: Path, cfg: dict) -> dict[str, tuple[str, str]]:
    """The functions the port writes itself, from the game's library table
    (port/game/<id>/libraries.tsv: symbol, library, name, port, notes,
    signature; port = host for those): symbol -> (name, signature). A row
    without a signature takes the shared one of its name."""
    out = {}
    table = cfg.get("libraries")
    if not table:
        return out
    api = library_api(config_dir, cfg)
    for line in (config_dir / table).read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) >= 4 and cols[3].strip() == "host":
            name = cols[2].strip()
            sig = cols[5].strip() if len(cols) > 5 and cols[5].strip() else api.get(name, "")
            out[cols[0].strip()] = (name, sig)
    return out


def wrapped(config_dir: Path, cfg: dict) -> set[str]:
    """Functions whose C is kept under <name>__game, for a host <name> that
    calls it (libraries.tsv rows with port = wrap)."""
    out = set()
    table = cfg.get("libraries")
    if not table:
        return out
    for line in (config_dir / table).read_text().splitlines():
        cols = line.split("\t")
        if not line.startswith("#") and len(cols) >= 4 and cols[3].strip() == "wrap":
            out.add(cols[0].strip())
    return out


def units_of(root: Path, cfg: dict) -> list[str]:
    units = []
    for src in cfg["sources"]:
        for p in sorted((root / src).rglob("*.c")):
            rel = p.relative_to(root).as_posix()
            if any(rel == s or rel.startswith(s.rstrip("/") + "/") for s in cfg["skip"]):
                continue
            units.append(rel)
    return units


