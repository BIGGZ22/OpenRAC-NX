"""The SDK's API reference, generated from its sources (sdk/docs/reference/).

    python3 sdk/tools/gen_reference.py [--check]

writes, from what the SDK ships, so that the reference never drifts from it:

    c-api.md         include/openrac/openrac_mod.h: versions, constants, types, the openrac_api table
    cpp-api.md       include/openrac/mod.hpp: the C++ layer's classes and their public members
    luau-api.md      types/<game>.d.luau: the `openrac` global a script mod sees
    hooks-<game>.md  bindings/<game>.json: the hook points (ids and aliases when the table has them),
                     the fields exposed to scripts, and the behaviour catalogue when the table names
                     one (experimental)

Each page says it is generated. --check writes nothing and fails when a page is not what the sources
give (CI: .github/workflows/sdk.yml). Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SDK = Path(__file__).resolve().parent.parent
ROOT = SDK.parent
HEADER = "<!-- Generated by sdk/tools/gen_reference.py from {source}. Do not edit: change the source and run it again. -->\n\n"


def cell(text: str) -> str:
    """Text for a Markdown table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def code(text: str) -> str:
    """Inline code for a Markdown table cell (a | is escaped there, inside code too)."""
    text = " ".join(text.split()).replace("|", "\\|")
    return f"`` {text} ``" if "`" in text else f"`{text}`"


def prose_and_code(text: str, lang: str) -> str:
    """A comment's text as Markdown: lines indented by two spaces or more are code, the rest prose."""
    out, block = [], []
    for line in text.splitlines() + [""]:
        if line.startswith("  "):
            block.append(line[2:])
            continue
        if block:
            out.append(f"```{lang}\n" + "\n".join(block).rstrip() + "\n```")
            block = []
        out.append(line)
    return "\n".join(out).strip() + "\n\n"


# ---- C: openrac_mod.h ----

def _strip_block(comment: str) -> str:
    body = comment.strip()
    body = re.sub(r"^/\*+", "", body)
    body = re.sub(r"\*+/$", "", body)
    lines = [re.sub(r"^\s*\*\s?", "", line).rstrip() for line in body.splitlines()]
    return "\n".join(lines).strip()


def parse_c_header(text: str) -> dict:
    """The header's items in order: #defines, typedefs and structs, each with the comment before it
    or on its line. Function-like or multi-line macros keep only their name and parameters."""
    out = {"intro": "", "defines": [], "typedefs": [], "structs": []}
    lines = text.splitlines()
    i = 0
    pending = ""
    first_block = True
    struct = None
    decl = ""
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if s.startswith("/*"):
            block = [line]
            while "*/" not in lines[i]:
                i += 1
                block.append(lines[i])
            comment = _strip_block("\n".join(block))
            rest = lines[i].split("*/", 1)[1].strip()
            i += 1
            if first_block:
                first_block = False
                kept = [l for l in comment.splitlines() if not l.startswith(("SPDX", "Copyright"))]
                out["intro"] = "\n".join(kept).strip()
                continue
            if not rest:
                pending = comment
                continue
            line, s = rest, rest
            i -= 1
        if struct is not None:
            if s.startswith("}"):
                struct["name"] = s.strip("}; ").strip() or struct["name"]
                out["structs"].append(struct)
                struct = None
                pending = ""
            elif s:
                inline = ""
                m = re.search(r"/\*(.*?)\*/", s)
                if m:
                    inline = m.group(1).strip()
                    s = (s[: m.start()] + s[m.end():]).strip()
                decl = (decl + " " + s).strip()
                if decl.endswith(";"):
                    struct["members"].append({"decl": decl[:-1].strip(), "about": inline or pending})
                    decl = ""
                    pending = ""
            else:
                pending = ""
            i += 1
            continue
        if s.startswith("#define") and not s.startswith(("#define OPENRAC_MOD_H",)):
            m = re.match(r"#define\s+(\w+(?:\([^)]*\))?)\s*(.*)", s)
            name, value = m.group(1), m.group(2)
            inline = ""
            cm = re.search(r"/\*(.*?)\*/", value)
            if cm:
                inline = cm.group(1).strip()
                value = (value[: cm.start()] + value[cm.end():]).strip()
            multi = value.endswith("\\")
            while lines[i].rstrip().endswith("\\"):
                i += 1
            if "(" in name or multi:
                value = ""
            out["defines"].append({"name": name, "value": value, "about": inline or pending})
            pending = ""
        elif re.match(r"typedef\s+struct\s+\w+\s*\{", s):
            struct = {"name": re.match(r"typedef\s+struct\s+(\w+)", s).group(1), "about": pending, "members": []}
            pending = ""
            decl = ""
        elif s.startswith("typedef"):
            full = s
            while not full.endswith(";"):
                i += 1
                full += " " + lines[i].strip()
            out["typedefs"].append({"decl": full, "about": pending})
            pending = ""
        elif s.startswith(("OPENRAC_MOD_EXPORT",)):
            pending = ""
        elif not s:
            pass
        else:
            pending = ""
        i += 1
    return out


def c_page(header: Path) -> str:
    h = parse_c_header(header.read_text())
    rel = header.relative_to(SDK).as_posix()
    out = [HEADER.format(source=f"sdk/{rel}"), "# The C interface: `openrac/openrac_mod.h`\n\n"]
    if h["intro"]:
        out.append(h["intro"] + "\n\n")
    out.append("## Macros and constants\n\n| Name | Value | |\n|---|---|---|\n")
    merged: dict[str, dict] = {}
    for d in h["defines"]:
        if d["name"] in merged:  # a platform's own spelling (#if ... #else)
            merged[d["name"]]["values"].append(d["value"])
        else:
            merged[d["name"]] = {"values": [d["value"]], "about": d["about"]}
    for name, d in merged.items():
        values = " or ".join(code(v) for v in d["values"] if v)
        out.append(f"| {code(name)} | {values} | {cell(d['about'])} |\n")
    out.append("\n## Types\n\n")
    for t in h["typedefs"]:
        out.append(f"```c\n{t['decl']}\n```\n\n")
        if t["about"]:
            out.append(t["about"] + "\n\n")
    for s in h["structs"]:
        out.append(f"## `{s['name']}`\n\n")
        if s["about"]:
            out.append(s["about"] + "\n\n")
        out.append("| Member | |\n|---|---|\n")
        for m in s["members"]:
            out.append(f"| {code(m['decl'])} | {cell(m['about'])} |\n")
        out.append("\n")
    return "".join(out).rstrip() + "\n"


# ---- C++: mod.hpp ----

def parse_cpp_header(text: str) -> dict:
    """The intro comment, the public classes of namespace openrac (not detail) with their public
    members and the comment lines before each, and the macros with theirs."""
    lines = text.splitlines()
    intro = []
    for line in lines:
        if not line.startswith("//"):
            break
        body = line[2:].strip()
        if not body.startswith(("SPDX", "Copyright")):
            intro.append(line[3:] if line.startswith("// ") else line[2:])
    classes = []
    macros = []
    depth = 0
    detail_depth = None
    current = None
    access = "private"
    comment: list[str] = []
    template = ""
    i = 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        opens, closes = s.count("{"), s.count("}")
        if s.startswith("namespace detail"):
            detail_depth = depth
        if s.startswith("//"):
            comment.append(s[2:].strip())
        elif s.startswith("#define") and depth == 0 and not s.startswith("#define OPENRAC_MOD_H"):
            m = re.match(r"#define\s+(\w+(?:\([^)]*\))?)", s)
            if m and comment:
                macros.append({"name": m.group(1), "about": " ".join(comment)})
            while lines[i].rstrip().endswith("\\"):
                i += 1
            comment = []
        elif s.startswith("template") and not s.endswith("{"):
            in_scope = detail_depth is None and (depth == 1 if current is None else depth == current["depth"])
            template = s if in_scope else ""
        elif detail_depth is None and current is None and re.match(r"(class|struct)\s+\w+[^;]*\{", s) and depth == 1:
            name = re.match(r"(?:class|struct)\s+(\w+)", s).group(1)
            current = {"name": name, "template": template, "about": " ".join(comment), "members": [], "depth": depth + 1}
            access = "public" if s.startswith("struct") else "private"
            comment, template = [], ""
        elif current is not None and depth == current["depth"]:
            if s in ("public:", "private:", "protected:"):
                access = s[:-1]
                comment = []
            elif s and access == "public" and "(" in s and not s.startswith(("return", "}")):
                decl = s
                while "{" not in decl and not decl.rstrip().endswith(";") and i + 1 < len(lines):
                    i += 1
                    decl += " " + lines[i].strip()
                    opens += lines[i].count("{")
                    closes += lines[i].count("}")
                sig = re.split(r"\s*(?::\s*\w+\(|\{|;)", decl, maxsplit=1)[0].strip()
                if template:
                    sig = template + " " + sig
                if "= delete" not in decl:
                    current["members"].append({"decl": sig, "about": " ".join(comment)})
                comment, template = [], ""
            elif s:
                comment, template = [], "" if not s.startswith("template") else template
        else:
            if s and not s.startswith("template"):
                comment = []
        depth += opens - closes
        if current is not None and depth < current["depth"]:
            del current["depth"]
            classes.append(current)
            current = None
        if detail_depth is not None and depth <= detail_depth:
            detail_depth = None
        i += 1
    return {"intro": "\n".join(intro).strip(), "classes": classes, "macros": macros}


def cpp_page(header: Path) -> str:
    h = parse_cpp_header(header.read_text())
    rel = header.relative_to(SDK).as_posix()
    out = [HEADER.format(source=f"sdk/{rel}"), "# The C++ layer: `openrac/mod.hpp`\n\n"]
    if h["intro"]:
        out.append(prose_and_code(h["intro"], "cpp"))
    for c in h["classes"]:
        title = f"openrac::{c['name']}"
        out.append(f"## `{title}`\n\n")
        if c["template"]:
            out.append(f"{code(c['template'])}\n\n")
        if c["about"]:
            out.append(c["about"] + "\n\n")
        if c["members"]:
            out.append("| Member | |\n|---|---|\n")
            for m in c["members"]:
                out.append(f"| {code(m['decl'])} | {cell(m['about'])} |\n")
            out.append("\n")
    if h["macros"]:
        out.append("## Macros\n\n| Macro | |\n|---|---|\n")
        for m in h["macros"]:
            out.append(f"| {code(m['name'])} | {cell(m['about'])} |\n")
    return "".join(out).rstrip() + "\n"


# ---- Luau: types/<game>.d.luau ----

def parse_luau_types(text: str) -> dict:
    """The type aliases (with the comment line before each) and the members of `declare openrac`."""
    types = []
    members = []
    lines = text.splitlines()
    comment = ""
    i = 0
    while i < len(lines):
        s = lines[i].strip()
        if s.startswith("--"):
            body = s[2:].strip()
            if not body.startswith(("Generated", "SPDX")):
                comment = body
        elif s.startswith("type "):
            block = [lines[i]]
            if s.endswith("{"):
                depth = s.count("{") - s.count("}")
                while depth > 0:
                    i += 1
                    block.append(lines[i])
                    depth += lines[i].count("{") - lines[i].count("}")
            name = re.match(r"type\s+(\w+)", s).group(1)
            types.append({"name": name, "text": "\n".join(block), "about": comment})
            comment = ""
        elif s.startswith("declare openrac"):
            i += 1
            while not lines[i].strip().startswith("}"):
                m = re.match(r"\s*(\w+)\s*:\s*(.*?),?\s*(--\s*(.*))?$", lines[i])
                if m:
                    members.append({"name": m.group(1), "type": m.group(2).rstrip(","), "about": m.group(4) or ""})
                i += 1
            comment = ""
        else:
            comment = ""
        i += 1
    return {"types": types, "members": members}


def luau_page(types_file: Path, game: str) -> str:
    t = parse_luau_types(types_file.read_text())
    rel = types_file.relative_to(SDK).as_posix()
    out = [HEADER.format(source=f"sdk/{rel}"),
           f"# The Luau API ({game})\n\n",
           "What a script mod sees: the global `openrac`, and these types. Point an editor's Luau\n"
           f"language server at the SDK's `{rel}` for autocomplete. How to use it: "
           "[script mods](../scripts.md).\n\n",
           "## `openrac`\n\n| Member | Type |\n|---|---|\n"]
    for m in t["members"]:
        out.append(f"| `openrac.{m['name']}` | {code(m['type'])} |\n")
    out.append("\n## Types\n\n")
    for ty in t["types"]:
        out.append(f"### `{ty['name']}`\n\n")
        if ty["about"]:
            out.append(f"{ty['about']}\n\n")
        out.append(f"```lua\n{ty['text']}\n```\n\n")
    return "".join(out).rstrip() + "\n"


# ---- Hook points: bindings/<game>.json ----

def hooks_page(table_file: Path) -> str:
    table = json.loads(table_file.read_text())
    game = table.get("game", table_file.stem)
    discs = table.get("discs", [])
    rel = table_file.relative_to(SDK).as_posix()
    out = [HEADER.format(source=f"sdk/{rel}"), f"# Hook points and fields: {game}\n\n",
           "Every hook point a mod can take ([hooks](../hooks.md)), and the game state exposed to\n"
           "scripts by name. Signatures use `void i32 u32 i64 u64 f32 i16 u16 i8 u8`; `u32` is also a\n"
           "game address.\n\n"]
    hooks = table.get("hooks", [])
    has_id = any("id" in h for h in hooks)
    has_alias = any(h.get("aliases") for h in hooks)
    out.append("## Hook points\n\n")
    head = (["Id"] if has_id else []) + ["Name"] + (["Aliases"] if has_alias else []) + \
        ["Signature", "Parameters", "Discs", ""]
    out.append("| " + " | ".join(head) + " |\n|" + "---|" * len(head) + "\n")
    for h in hooks:
        row = ([code(h["id"]) if h.get("id") else ""] if has_id else []) + [code(h["name"])]
        if has_alias:
            row.append(", ".join(code(a) for a in h.get("aliases", [])))
        row += [code(h["signature"]), ", ".join(h.get("params", [])),
                ", ".join(d for d in discs if d in h.get("symbols", {})) or ", ".join(h.get("symbols", {})),
                cell(h.get("about", ""))]
        out.append("| " + " | ".join(row) + " |\n")
    fields = table.get("fields", [])
    if fields:
        out.append("\n## Fields\n\n**Experimental**: these name the game's internals and follow the decompilation.\n"
                   "In a script, `openrac.fields.<name>`.\n\n| Name | Type | Read-only | Discs | |\n|---|---|---|---|---|\n")
        bases = table.get("bases", {})
        for f in fields:
            if "address" in f:
                on = [d for d in discs if d in f["address"]]
            else:
                on = [d for d in discs if d in bases.get(f.get("base", ""), {})]
            out.append(f"| {code(f['name'])} | {code(f['type'])} | {'yes' if f.get('readonly') else ''} | "
                       f"{', '.join(on)} | {cell(f.get('about', ''))} |\n")
    # The catalogue's hook points as the binding's generator makes them (their ids, aliases and
    # classes), so this page lists what a mod can actually take.
    if table.get("catalogue"):
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import gen_binding  # noqa: E402

        merged = gen_binding.load(game, table_path=table_file)
        moby = [h for h in merged["hooks"] if h.get("origin") == "catalogue"]
        out.append("\n## Moby updates from the behaviour catalogue\n\n"
                   "**Experimental**: the catalogue is generated from the decompilation and names its\n"
                   "internals. One hook point per update function; a function several classes share is\n"
                   f"one hook point, which a mod filters by the moby's class. {len(moby)} hook points.\n\n"
                   "| Id | Classes | Signature | Also named |\n|---|---|---|---|\n")
        for h in sorted(moby, key=lambda h: h["id"]):
            classes = ", ".join(str(c) for c in h.get("classes", []))
            aliases = ", ".join(code(a) for a in sorted(h.get("aliases", [])) if not a.startswith(("func_", "FUN_")))
            out.append(f"| {code(h['id'])} | {classes} | {code(h['signature'])} | {aliases} |\n")
    return "".join(out).rstrip() + "\n"


# ---- All of it ----

def pages(sdk: Path = SDK) -> dict[str, str]:
    out = {"c-api.md": c_page(sdk / "include" / "openrac" / "openrac_mod.h"),
           "cpp-api.md": cpp_page(sdk / "include" / "openrac" / "mod.hpp")}
    for table in sorted((sdk / "bindings").glob("*.json")):
        out[f"hooks-{table.stem}.md"] = hooks_page(table)
    for types in sorted((sdk / "types").glob("*.d.luau")):
        game = types.name.split(".")[0]
        out["luau-api.md" if game == "rac1" else f"luau-api-{game}.md"] = luau_page(types, game)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; fail when a page is stale")
    args = ap.parse_args(argv)
    out_dir = SDK / "docs" / "reference"
    stale = []
    for name, text in pages().items():
        path = out_dir / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(name)
        else:
            out_dir.mkdir(parents=True, exist_ok=True)
            if not path.is_file() or path.read_text() != text:
                path.write_text(text)
                print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("gen_reference: stale (run python3 sdk/tools/gen_reference.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
