"""Tests of gen_reference.py and of the SDK's docs: python3 -m unittest discover -s sdk/tools"""
import json
import re
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_reference  # noqa: E402

SDK = Path(__file__).resolve().parent.parent
DOCS = SDK / "docs"


def anchors(text: str) -> set[str]:
    """GitHub's heading anchors of a Markdown page."""
    out = set()
    for line in text.splitlines():
        m = re.match(r"#+\s+(.*)", line)
        if m:
            slug = re.sub(r"[^\w\- ]", "", m.group(1).strip().lower()).replace(" ", "-")
            out.add(slug)
    return out


class Reference(unittest.TestCase):
    def test_reference_is_current(self):
        stale = [n for n, t in gen_reference.pages().items()
                 if not (DOCS / "reference" / n).is_file() or (DOCS / "reference" / n).read_text() != t]
        self.assertEqual(stale, [], "run python3 sdk/tools/gen_reference.py")

    def test_every_page_says_it_is_generated(self):
        for name, text in gen_reference.pages().items():
            self.assertTrue(text.startswith("<!-- Generated by sdk/tools/gen_reference.py"), name)

    def test_c_header(self):
        h = gen_reference.parse_c_header(
            "/* intro */\n"
            "#define A 1 /* one */\n"
            "/* The table. */\n"
            "typedef struct t {\n"
            "    int x; /* an x */\n"
            "    /* A function\n     * on two lines. */\n"
            "    int (*f)(int a,\n             int b);\n"
            "} t;\n")
        self.assertEqual(h["intro"], "intro")
        self.assertEqual(h["defines"][0], {"name": "A", "value": "1", "about": "one"})
        s = h["structs"][0]
        self.assertEqual(s["about"], "The table.")
        self.assertEqual([m["decl"] for m in s["members"]], ["int x", "int (*f)(int a, int b)"])
        self.assertEqual(s["members"][1]["about"], "A function\non two lines.")

    def test_cpp_header_keeps_public_members_only(self):
        h = gen_reference.parse_cpp_header(
            "// intro\n#pragma once\nnamespace openrac {\n"
            "namespace detail {\ntemplate <class T>\nstruct Hidden { void no(); };\n}\n"
            "// A thing.\nclass Thing {\npublic:\n"
            "    // Gets it.\n    int get() const { return 1; }\n"
            "    template <class T>\n    T as() const {\n        return T();\n    }\n"
            "private:\n    void secret();\n};\n}\n")
        self.assertEqual([c["name"] for c in h["classes"]], ["Thing"])
        members = h["classes"][0]["members"]
        self.assertEqual([m["decl"] for m in members], ["int get() const", "template <class T> T as() const"])
        self.assertEqual(members[0]["about"], "Gets it.")
        self.assertEqual(h["classes"][0]["template"], "")

    def test_hooks_with_ids_aliases_and_a_catalogue(self):
        with tempfile.TemporaryDirectory() as d:
            cat = Path(d) / "cat.json"
            cat.write_text(json.dumps({"format": 1, "game": "x", "classes": [
                {"name": "Crate", "class": 500, "id": "x.moby.crate.update", "update": {"pal": "f"}},
                {"name": "Rock", "class": 501}]}))
            table = Path(d) / "x.json"
            table.write_text(json.dumps({
                "format": 1, "game": "x", "discs": ["pal"], "catalogue": str(cat),
                "hooks": [{"id": "x.player.jump", "name": "Hero_Jump", "aliases": ["Jump"],
                           "signature": "void(f32)", "params": ["height"], "symbols": {"pal": "f"}}]}))
            # The page names its source relative to the SDK; a table elsewhere is given a stand-in.
            real = gen_reference.SDK
            try:
                gen_reference.SDK = Path(d)
                page = gen_reference.hooks_page(table)
            finally:
                gen_reference.SDK = real
        self.assertIn("| Id | Name | Aliases | Signature |", page)
        self.assertIn("| `x.player.jump` | `Hero_Jump` | `Jump` | `void(f32)` | height | pal |", page)
        self.assertIn("**Experimental**", page)
        self.assertIn("`x.moby.crate.update`", page)
        self.assertNotIn("Rock", page)

    def test_luau_types(self):
        t = gen_reference.parse_luau_types(
            "-- Generated\n\ntype K = \"a\" | \"b\"\n-- The fields.\ntype F = {\n    x: number,\n}\n"
            "declare openrac: {\n    game: string,\n    log: (...any) -> (), -- the log\n}\n")
        self.assertEqual([x["name"] for x in t["types"]], ["K", "F"])
        self.assertEqual(t["types"][1]["about"], "The fields.")
        self.assertEqual(t["members"], [{"name": "game", "type": "string", "about": ""},
                                        {"name": "log", "type": "(...any) -> ()", "about": "the log"}])


if __name__ == "__main__":
    unittest.main()
